package days03;

public class Ex08_03 {

	public static void main(String[] args) {
		
		int i = 10, j = 3;
	
		
		System.out.println(i==j); // == 두개
		//The operator ! is undefined for the argument type(s) int
		System.out.println(i!=j); 
		
		System.out.println(i>j); 
		System.out.println(i<j); 
		
		System.out.println(i<=j); 
		System.out.println(i>=j); 
		
		

	}//main

}//class
