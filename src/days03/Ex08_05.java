public class Ex08_05 {

	public static void main(String[] args) {
		
		int n = 10; // 대입연산자
		System.out.printf("n=%d\n",n);
		n += 5; //n=n + 5 ;
		System.out.printf("n=%d\n",n);
		n -= 3; // n= n-3
		System.out.printf("n=%d\n",n);
		n *= 2; // n=n*2
		System.out.printf("n=%d\n",n);
		
		
		
		
	}

}
